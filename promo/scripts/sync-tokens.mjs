/**
 * Copies the app's design tokens and utilities (src/app/globals.css) into the promo, minus the
 * app-only imports, so the videos render with exactly the app's colours, radii, type and materials.
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../../src/app/globals.css", import.meta.url);
const out = new URL("../src/styles/app-tokens.css", import.meta.url);
const css = readFileSync(src, "utf8")
  .split("\n")
  .filter((l) => !/^@import |^@source /.test(l))
  .join("\n");
writeFileSync(out, `/* GENERATED by scripts/sync-tokens.mjs from src/app/globals.css: do not edit. */\n${css}`);
console.log(`wrote ${out.pathname}`);
